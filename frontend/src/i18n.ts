export function t(lang: Language, key: string): string {
  return T[key]?.[lang] ?? T[key]?.en ?? T["INTERNAL_ERROR"][lang];
}

/** Maps any thrown value to translated, user-facing text. */
export function errText(lang: Language, e: unknown): string {
  const code = (e as { code?: string } | null)?.code;
  return t(lang, code && T[code] ? code : "INTERNAL_ERROR");
}

export function formatMonth(month: string, lang: Language): string {
  const [y, m] = month.split("-").map(Number);
  return new Intl.DateTimeFormat(lang === "hi" ? "hi-IN" : "en-IN", { month: "long", year: "numeric" }).format(new Date(y, m - 1, 1));
}
